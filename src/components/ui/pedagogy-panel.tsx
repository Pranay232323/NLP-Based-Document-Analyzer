"use client";

import { useState } from "react";
import { Card, CardBody, CardHeader, Badge } from "@/components/ui/primitives";
import type { ExperimentPedagogy, LinguisticPreset } from "@/lib/nlp/pedagogy";
import {
  GraduationCap,
  HelpCircle,
  FileCheck,
  CheckCircle2,
  XCircle,
  ChevronDown,
  ChevronUp,
  Download,
  Printer,
  Sparkles,
  BookOpen,
  Cpu,
  Clock,
  Layers,
} from "lucide-react";

interface PedagogyPanelProps {
  pedagogy: ExperimentPedagogy;
  onApplyPreset?: (text: string) => void;
}

export function PedagogyPanel({ pedagogy, onApplyPreset }: PedagogyPanelProps) {
  const [activeTab, setActiveTab] = useState<"viva" | "quiz" | "manual">("viva");
  const [expandedVivaIndex, setExpandedVivaIndex] = useState<number | null>(0);
  const [selectedAnswers, setSelectedAnswers] = useState<Record<string, number>>({});
  const [quizSubmitted, setQuizSubmitted] = useState<Record<string, boolean>>({});

  function handleSelectOption(qId: string, optIndex: number) {
    setSelectedAnswers((prev) => ({ ...prev, [qId]: optIndex }));
    setQuizSubmitted((prev) => ({ ...prev, [qId]: true }));
  }

  function handleExportMarkdown() {
    const { labManual, complexity, vivaQuestions } = pedagogy;
    const content = `# Practical ${labManual.experimentNumber}: ${labManual.title}
**Course**: Natural Language Processing (NLP) Laboratory
**Generated by**: NLP Intelligence Platform & Academic Research Assistant

---

## 1. Aim / Objective
${labManual.aim}

## 2. Computational Complexity
- **Time Complexity**: ${complexity.time}
- **Space Complexity**: ${complexity.space}

## 3. Theoretical Principles
${labManual.theory}

## 4. Algorithmic Procedure
${labManual.algorithm.map((step) => `${step}`).join("\n")}

## 5. Viva Voce Key Concepts & Model Answers
${vivaQuestions
  .map(
    (v, i) => `### Q${i + 1}: ${v.question}
**Answer**: ${v.answer}
${v.tip ? `*Examiner Tip*: ${v.tip}` : ""}`
  )
  .join("\n\n")}

## 6. Academic Conclusion
${labManual.conclusionTemplate}
`;

    const blob = new Blob([content], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `Practical-${labManual.experimentNumber}-${pedagogy.id}-Journal.md`;
    a.click();
    URL.revokeObjectURL(url);
  }

  return (
    <Card className="border-indigo-100 shadow-sm overflow-hidden">
      <CardHeader
        title={`🎓 Student Learning & Exam Hub · Practical ${pedagogy.practicalNumber}`}
        subtitle="Viva Voce questions with examiner answers, concept self-check quiz, and college lab journal generator."
        action={
          <div className="flex flex-wrap items-center gap-1.5">
            <span className="inline-flex items-center gap-1 rounded bg-slate-100 px-2 py-0.5 text-[11px] font-mono text-slate-700">
              <Clock className="h-3 w-3 text-indigo-500" />
              {pedagogy.complexity.time}
            </span>
            <span className="inline-flex items-center gap-1 rounded bg-slate-100 px-2 py-0.5 text-[11px] font-mono text-slate-700">
              <Layers className="h-3 w-3 text-purple-500" />
              {pedagogy.complexity.space}
            </span>
          </div>
        }
      />

      <div className="border-b border-slate-100 bg-slate-50/70 px-5 pt-2">
        <div className="flex gap-2">
          <button
            onClick={() => setActiveTab("viva")}
            className={`flex items-center gap-1.5 border-b-2 px-3 py-2 text-xs font-semibold transition ${
              activeTab === "viva"
                ? "border-indigo-600 text-indigo-600"
                : "border-transparent text-slate-600 hover:text-slate-900"
            }`}
          >
            <GraduationCap className="h-3.5 w-3.5" />
            Viva Voce Oral Exam Prep ({pedagogy.vivaQuestions.length})
          </button>

          <button
            onClick={() => setActiveTab("quiz")}
            className={`flex items-center gap-1.5 border-b-2 px-3 py-2 text-xs font-semibold transition ${
              activeTab === "quiz"
                ? "border-indigo-600 text-indigo-600"
                : "border-transparent text-slate-600 hover:text-slate-900"
            }`}
          >
            <HelpCircle className="h-3.5 w-3.5" />
            Concept Self-Check Quiz ({pedagogy.quiz.length})
          </button>

          <button
            onClick={() => setActiveTab("manual")}
            className={`flex items-center gap-1.5 border-b-2 px-3 py-2 text-xs font-semibold transition ${
              activeTab === "manual"
                ? "border-indigo-600 text-indigo-600"
                : "border-transparent text-slate-600 hover:text-slate-900"
            }`}
          >
            <FileCheck className="h-3.5 w-3.5" />
            Lab Journal Practical Record
          </button>
        </div>
      </div>

      <CardBody className="p-5">
        {/* ================================================================= */}
        {/* TAB 1: VIVA VOCE QUESTIONS                                        */}
        {/* ================================================================= */}
        {activeTab === "viva" && (
          <div className="space-y-3">
            <p className="text-xs text-slate-500">
              Frequently asked questions in university oral practical examinations with model academic answers:
            </p>

            <div className="space-y-2">
              {pedagogy.vivaQuestions.map((q, idx) => {
                const isExpanded = expandedVivaIndex === idx;
                return (
                  <div
                    key={idx}
                    className="overflow-hidden rounded-xl border border-slate-200 bg-white transition"
                  >
                    <button
                      onClick={() => setExpandedVivaIndex(isExpanded ? null : idx)}
                      className="flex w-full items-center justify-between p-3.5 text-left text-xs font-semibold text-slate-800 hover:bg-slate-50"
                    >
                      <span className="flex items-center gap-2">
                        <span className="flex h-5 w-5 shrink-0 items-center justify-center rounded-full bg-indigo-100 text-[11px] font-bold text-indigo-700">
                          {idx + 1}
                        </span>
                        <span>{q.question}</span>
                      </span>
                      <div className="flex items-center gap-2">
                        <span className="hidden text-[10px] font-medium text-slate-400 sm:inline">
                          {q.category}
                        </span>
                        {isExpanded ? (
                          <ChevronUp className="h-4 w-4 text-slate-400" />
                        ) : (
                          <ChevronDown className="h-4 w-4 text-slate-400" />
                        )}
                      </div>
                    </button>

                    {isExpanded && (
                      <div className="border-t border-slate-100 bg-slate-50/60 p-4 text-xs space-y-2">
                        <div className="text-slate-700 leading-relaxed">
                          <strong className="text-slate-900">Model Answer: </strong>
                          {q.answer}
                        </div>
                        {q.tip && (
                          <div className="flex items-start gap-1.5 rounded-lg border border-indigo-100 bg-indigo-50/50 p-2 text-[11px] text-indigo-900">
                            <Sparkles className="h-3.5 w-3.5 shrink-0 text-indigo-600 mt-0.5" />
                            <span>
                              <strong>Examiner Pro-Tip:</strong> {q.tip}
                            </span>
                          </div>
                        )}
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
          </div>
        )}

        {/* ================================================================= */}
        {/* TAB 2: INTERACTIVE SELF-CHECK QUIZ                                */}
        {/* ================================================================= */}
        {activeTab === "quiz" && (
          <div className="space-y-4">
            <p className="text-xs text-slate-500">
              Test your understanding before the practical viva. Instant feedback with pedagogical explanations:
            </p>

            <div className="space-y-4">
              {pedagogy.quiz.map((q, qIdx) => {
                const userChoice = selectedAnswers[q.id];
                const isAnswered = quizSubmitted[q.id];

                return (
                  <div
                    key={q.id}
                    className="rounded-xl border border-slate-200 bg-white p-4 text-xs space-y-3"
                  >
                    <div className="font-semibold text-slate-900">
                      Q{qIdx + 1}: {q.question}
                    </div>

                    <div className="space-y-1.5">
                      {q.options.map((opt, optIdx) => {
                        const isSelected = userChoice === optIdx;
                        const isCorrect = optIdx === q.correctIndex;

                        let style = "border-slate-200 hover:bg-slate-50 text-slate-700";
                        if (isAnswered) {
                          if (isCorrect) {
                            style = "border-emerald-500 bg-emerald-50 text-emerald-900 font-semibold";
                          } else if (isSelected && !isCorrect) {
                            style = "border-rose-400 bg-rose-50 text-rose-900";
                          }
                        } else if (isSelected) {
                          style = "border-indigo-500 bg-indigo-50 text-indigo-900 font-semibold";
                        }

                        return (
                          <button
                            key={optIdx}
                            onClick={() => handleSelectOption(q.id, optIdx)}
                            className={`flex w-full items-center justify-between rounded-lg border p-2.5 text-left transition ${style}`}
                          >
                            <span>{opt}</span>
                            {isAnswered && (
                              <span>
                                {isCorrect ? (
                                  <CheckCircle2 className="h-4 w-4 text-emerald-600 shrink-0" />
                                ) : isSelected ? (
                                  <XCircle className="h-4 w-4 text-rose-600 shrink-0" />
                                ) : null}
                              </span>
                            )}
                          </button>
                        );
                      })}
                    </div>

                    {isAnswered && (
                      <div
                        className={`rounded-lg p-2.5 text-[11px] leading-relaxed ${
                          userChoice === q.correctIndex
                            ? "bg-emerald-50 text-emerald-900 border border-emerald-200"
                            : "bg-slate-50 text-slate-700 border border-slate-200"
                        }`}
                      >
                        <strong>Explanation: </strong>
                        {q.explanation}
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
          </div>
        )}

        {/* ================================================================= */}
        {/* TAB 3: UNIVERSITY LAB MANUAL JOURNAL GENERATOR                     */}
        {/* ================================================================= */}
        {activeTab === "manual" && (
          <div className="space-y-4">
            <div className="flex flex-wrap items-center justify-between gap-2 rounded-xl border border-indigo-200 bg-indigo-50/50 p-3">
              <div>
                <h4 className="text-xs font-bold text-indigo-950">
                  Ready-to-Submit University Laboratory Journal Record
                </h4>
                <p className="text-[11px] text-slate-600">
                  Formatted in official academic journal standards (Aim, Theory, Algorithm, Conclusion).
                </p>
              </div>
              <div className="flex items-center gap-2">
                <button
                  onClick={handleExportMarkdown}
                  className="flex items-center gap-1.5 rounded-lg bg-indigo-600 px-3 py-1.5 text-xs font-semibold text-white hover:bg-indigo-700 shadow-xs transition"
                >
                  <Download className="h-3.5 w-3.5" />
                  Download Journal (.md)
                </button>
                <button
                  onClick={() => window.print()}
                  className="flex items-center gap-1.5 rounded-lg border border-slate-200 bg-white px-3 py-1.5 text-xs font-semibold text-slate-700 hover:bg-slate-100 transition"
                >
                  <Printer className="h-3.5 w-3.5" />
                  Print / Save PDF
                </button>
              </div>
            </div>

            {/* Preview Document Box */}
            <div className="rounded-xl border border-slate-200 bg-white p-5 text-xs space-y-4 text-slate-800 shadow-xs">
              <div className="border-b border-slate-100 pb-3">
                <span className="text-[10px] font-bold uppercase tracking-wider text-indigo-600">
                  Department of Computer Science &amp; Engineering · NLP Lab
                </span>
                <h3 className="mt-1 text-sm font-bold text-slate-900">
                  Practical {pedagogy.labManual.experimentNumber}: {pedagogy.labManual.title}
                </h3>
              </div>

              <div>
                <span className="font-bold text-slate-900 uppercase tracking-wide text-[11px]">Aim:</span>
                <p className="mt-1 leading-relaxed text-slate-600">{pedagogy.labManual.aim}</p>
              </div>

              <div>
                <span className="font-bold text-slate-900 uppercase tracking-wide text-[11px]">Theoretical Principles:</span>
                <p className="mt-1 leading-relaxed text-slate-600">{pedagogy.labManual.theory}</p>
              </div>

              <div>
                <span className="font-bold text-slate-900 uppercase tracking-wide text-[11px]">Algorithmic Steps:</span>
                <ol className="mt-1 space-y-1 text-slate-600 pl-4 list-decimal">
                  {pedagogy.labManual.algorithm.map((step, idx) => (
                    <li key={idx}>{step}</li>
                  ))}
                </ol>
              </div>

              <div>
                <span className="font-bold text-slate-900 uppercase tracking-wide text-[11px]">Academic Conclusion:</span>
                <p className="mt-1 leading-relaxed text-slate-600 bg-slate-50 p-2.5 rounded border border-slate-100">
                  {pedagogy.labManual.conclusionTemplate}
                </p>
              </div>
            </div>
          </div>
        )}
      </CardBody>
    </Card>
  );
}

// ---------------------------------------------------------------------------
// TEACHER & STUDENT LINGUISTIC PRESETS BAR COMPONENT
// ---------------------------------------------------------------------------
interface LinguisticPresetsBarProps {
  presets: LinguisticPreset[];
  onSelect: (text: string) => void;
}

export function LinguisticPresetsBar({ presets, onSelect }: LinguisticPresetsBarProps) {
  if (!presets || presets.length === 0) return null;

  return (
    <div className="flex flex-wrap items-center gap-1.5 rounded-xl border border-indigo-100 bg-indigo-50/40 p-2.5 text-xs">
      <span className="flex items-center gap-1 font-semibold text-indigo-950">
        <Sparkles className="h-3.5 w-3.5 text-indigo-600" />
        Teacher Edge-Case Presets:
      </span>
      {presets.map((preset, idx) => (
        <button
          key={idx}
          onClick={() => onSelect(preset.text)}
          title={preset.teachingPoint}
          className="group relative flex items-center gap-1 rounded-md border border-indigo-200 bg-white px-2 py-1 text-[11px] font-medium text-slate-700 hover:border-indigo-400 hover:bg-indigo-50 transition shadow-2xs"
        >
          <span>{preset.label}</span>
          <span className="rounded bg-slate-100 px-1 py-0.2 text-[9px] text-slate-500 font-mono">
            {preset.language}
          </span>
        </button>
      ))}
    </div>
  );
}
